var sep = "   "; // 3 spaces uniform kerning

function generateAscii(text) {
  if (!text || text.length === 0) return "";
  var clean = text.toUpperCase();
  var lines = ["", "", "", "", "", "", "", ""];

  for (var i = 0; i < clean.length; i++) {
    var char = clean.charAt(i);
    var glyph = GLYPHS[char] || GLYPHS[" "];
    for (var r = 0; r < 8; r++) {
      lines[r] += (lines[r].length > 0 ? sep : "") + glyph[r];
    }
  }

  return lines.map(function(l) { return l.replace(/\s+$/, ""); }).join("\n");
}

